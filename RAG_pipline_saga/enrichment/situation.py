"""
situation.py — a structured picture of what is happening around a subject.

Built only from tool outputs already computed by the database:

    volume        exact count in the window              (aggregate)
    movement      this window vs the previous one        (trend)
    where         counts per district                    (aggregate by districts)
    who           authors / accounts that recur          (aggregate by handle + records)
    what          topics and risk levels                 (aggregate)
    connections   records that share accounts, targets or places (related + entities)
    signals       high-risk counts, negative-sentiment share

Every number is copied from a tool result and points at the evidence it came
from. The situation states observations ("12 high-risk alerts, 9 of them
naming the same two accounts"); it does not conclude intent, cause or guilt,
and `observations` are generated by fixed templates, not a model.
"""

from __future__ import annotations

from typing import Dict, List, Optional

from . import entities


def _top(rows: List[dict], n: int = 5) -> List[dict]:
    return [r for r in rows if r.get("value") not in (None, "")][:n]


def build(subject: str, *, records: List[dict], total: Optional[int],
          breakdowns: Dict[str, List[dict]], trend: Optional[dict],
          related: List[dict], window_days: int,
          latest_available: Optional[str] = None) -> dict:
    risk = {r["value"]: r["count"] for r in breakdowns.get("risk_level", [])}
    sentiment = {r["value"]: r["count"] for r in breakdowns.get("sentiment", [])}
    recurring = entities.repeated(records + related, min_count=2)
    clusters = []
    for rel in related[:10]:
        if rel.get("shared"):
            clusters.append({"record": rel.get("key"), "shared": rel["shared"],
                             "signals": rel.get("signals", [])})

    obs: List[str] = []
    if total is not None:
        obs.append(f"{total} matching record(s) in the last {window_days} day(s).")
        # An empty period over a corpus that stopped updating reads exactly like
        # a broken assistant. Naming the newest record says which it is.
        if not total and latest_available:
            obs.append(f"No records fall in that period. The most recent record in "
                       f"your scope is from {str(latest_available)[:10]}, so the "
                       f"data may not be current.")
    if trend and trend.get("previous") is not None:
        if trend.get("change_pct") is None:
            obs.append(f"{trend['current']} in this window; none in the window before, so no "
                       f"percentage change is stated.")
        elif trend.get("comparable") is False:
            # Too small a base to divide by: the counts say more than the ratio.
            obs.append(f"{trend['current']} in this window against {trend['previous']} in the "
                       f"previous one — too few before to state a percentage.")
        else:
            obs.append(f"{trend['current']} in this window against {trend['previous']} in the "
                       f"previous one ({trend['change_pct']:+}%).")
    if risk.get("high"):
        obs.append(f"{risk['high']} record(s) are rated high risk.")
    # What the records are ABOUT is the closest thing to a list of distinct
    # situations, and it is the first thing an officer needs. It was being
    # computed into `topics` below and then never said out loud.
    top_topics = _top(breakdowns.get("topics", []), 5)
    if top_topics:
        obs.append("Main subjects: " + ", ".join(
            f"{str(r['value']).replace('_', ' ')} ({r['count']})" for r in top_topics) + ".")
    top_places = _top(breakdowns.get("districts", []), 3)
    if top_places:
        obs.append("Most records are in " + ", ".join(f"{r['value']} ({r['count']})"
                                                       for r in top_places) + ".")
    acct = [e for e in recurring if e["type"] == "account"][:3]
    if acct:
        obs.append("Accounts appearing repeatedly: " + ", ".join(
            f"@{e['text']} ({e['count']})" for e in acct) + ".")
    if clusters:
        obs.append(f"{len(clusters)} related record(s) share an account, target or place with "
                   f"the matches.")

    return {
        "subject": subject,
        "window_days": window_days,
        "volume": total,
        "movement": trend,
        "where": _top(breakdowns.get("districts", []), 10),
        "who": _top(breakdowns.get("handle", []), 10),
        "topics": _top(breakdowns.get("topics", []), 10),
        "risk": risk,
        "sentiment": sentiment,
        "recurring_entities": recurring[:15],
        "connections": clusters,
        "observations": obs,
    }
